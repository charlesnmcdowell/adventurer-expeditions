'use strict';
// Story difficulty (Hiro, 2026-10-13): "I'd like hiro to die in 3 to 4 direct hits".
// Measures every campaign opponent's ordinary direct hit on Hiro, with the
// edition's old damage multipliers switched off, and writes one multiplier per
// opponent into the generated block of js/expedition/story_combat.js so that a
// direct hit takes SHARE of Hiro's health: about 3.5 hits for regular foes, 3 for
// bosses and named characters. Rerun after new opponents are registered:
//
//   node tools/story_hit_scale.js           measure and rewrite the block
//   node tools/story_hit_scale.js --check   fail if an opponent has no entry
const fs = require('node:fs'), vm = require('node:vm'), path = require('node:path');
const ROOT = path.resolve(__dirname, '..'); process.chdir(ROOT);
const SHARE = { regular: 0.28, boss: 0.33 };
const FILE = 'js/expedition/story_combat.js', START = '// HIT SCALE: generated by tools/story_hit_scale.js. Do not edit by hand.', END = '// END HIT SCALE';
const A = require('../test/harness').load();
for (const n of ['data', 'shim', 'encounter', 'campaign', 'run', 'story', 'story_combat']) vm.runInThisContext(fs.readFileSync('js/expedition/' + n + '.js', 'utf8'));
const X = A.Expedition, S = X.Story, E = X.Encounter, B = S.Combat; let clock = 0; X.now = () => clock;
const data = JSON.parse(fs.readFileSync('assets/expedition/story/campaign.json'));
const boss = id => /^(named|mini):/.test(id);

if (process.argv.includes('--check')) {
  const missing = data.combatRoster.map(e => e.kind + ':' + e.id).filter(id => !(B.hitScale && B.hitScale[id]));
  if (missing.length) { console.error('No hit scale for: ' + missing.join(', ')); process.exit(1); }
  console.log('story hit scale: every opponent has an entry'); process.exit(0);
}

// Raw numbers: no edition multipliers, the source campaign's own still applies.
B.hitScale = {}; B.enemyDamage = {}; B.encounterDamage = {}; B.tuning.foeDamage = B.tuning.laterFoeDamage = 1;
for (const e of data.combatRoster) S.bindings[e.kind + ':' + e.id] = { actor: 'SIMULATION_ONLY', combatReady: true, hiroFinishersReady: 2, enemyFinisherReady: true };
const hits = {}; let heroHp = 0;
for (const q of A.DATA.CAMPAIGN3_QUESTS) for (let i = 0; i < q.enc.length; i++) for (let seed = 1; seed <= 8; seed++) {
  const s = S.open(); s.record.chapter = q.n; s.record.encounter = i; s.record.phase = 'combat'; s.record.run.tutorial.skipGuide = true;
  const state = A.Campaign3.state(s.game); state.stage = q.n - 1; A.GatePerks.reconcile(s.game); S.syncQuest(s);
  let e; try { e = B.create(s, seed); } catch (err) { continue; }
  heroHp = E.heroUnit(e).maxHp;
  // Finisher only: no Counter, so ordinary hits land and can be measured.
  while (!e.st.over && e.steps < 400) { clock += 3500; if (E.skillState(e, 'finisher').ready) { E.requestSkill(e, 'finisher'); E.castNow(e); } if (!e.st.over) E.step(e); }
  for (const ev of e.st.events) {
    if (ev.t !== 'damage' || ev.uid !== e.heroUid || ev.tag === 'dot' || !ev.by || !(ev.dmg > 0)) continue;
    const u = e.st.units.find(x => x.uid === ev.by), id = u && u.ch.storyOpponent; if (!id) continue;
    (hits[id] = hits[id] || []).push(ev.dmg);
  }
}
const scale = {}, rows = [];
for (const [id, list] of Object.entries(hits).sort()) {
  list.sort((a, b) => a - b);
  const typical = list[Math.floor(list.length / 2)];             // median: one big skill must not set the rule
  const want = (boss(id) ? SHARE.boss : SHARE.regular) * heroHp;
  scale[id] = Math.round(want / typical * 100) / 100;
  rows.push({ id, hits: list.length, medianHit: typical, scale: scale[id], hitsToDie: +(heroHp / (typical * scale[id])).toFixed(1) });
}
console.table(rows);
const missing = data.combatRoster.map(e => e.kind + ':' + e.id).filter(id => !scale[id]);
if (missing.length) console.log('No hits measured (they keep the old multiplier): ' + missing.join(', '));
let src = fs.readFileSync(FILE, 'utf8'); const crlf = src.includes('\r\n'); src = src.replace(/\r\n/g, '\n');
const block = START + '\n// Multiplier per opponent so a direct hit takes ' + SHARE.regular + ' of Hiro\'s health (' + SHARE.boss + ' for bosses and named characters), measured at Hiro ' + heroHp + ' HP.\nB.hitScale=' + JSON.stringify(scale) + ';\n' + END;
const a = src.indexOf(START), b = src.indexOf(END);
if (a < 0 || b < a) throw Error('Generated block markers missing in ' + FILE);
src = src.slice(0, a) + block + src.slice(b + END.length);
if (crlf) src = src.replace(/\n/g, '\r\n');
fs.writeFileSync(FILE, src);
console.log('Wrote ' + Object.keys(scale).length + ' opponent multipliers to ' + FILE);
