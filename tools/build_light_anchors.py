"""Locate painted warm windows/lanterns for registered, bounded light flicker."""
from pathlib import Path
import json
from PIL import Image
import numpy as np
from scipy import ndimage
ROOT=Path(__file__).resolve().parents[1]
out={}
for group in ['travel','stages']:
    for folder in (ROOT/'assets/expedition'/group).iterdir():
        if not folder.is_dir():continue
        layers={}
        for filename in ['atmosphere-far.webp','atmosphere-ground.webp','plate.webp']:
            p=folder/filename
            if not p.exists():continue
            a=np.array(Image.open(p).convert('RGBA'));h,w=a.shape[:2];r,g,b=[a[:,:,n].astype(float) for n in range(3)]
            mask=(r>205)&(g>130)&(b<135)&(r>b*1.5)&(a[:,:,3]>200)
            lab,n=ndimage.label(mask);hits=[]
            for i,sl in enumerate(ndimage.find_objects(lab),1):
                if sl is None:continue
                yy,xx=np.where(lab[sl]==i);size=len(xx)
                if 3<=size<=170 and sl[0].stop-sl[0].start<30 and sl[1].stop-sl[1].start<24:
                    x=float(xx.mean()+sl[1].start);y=float(yy.mean()+sl[0].start)
                    # Only city/magical architecture and marsh lanterns. Sunny
                    # coastal rock/forest highlights must never look like fire.
                    if any(k in folder.name for k in ['city','citadel','swamp']):hits.append((size,x/w,y/h))
            points=[]
            for size,x,y in sorted(hits,reverse=True):
                if all((x-px)**2+(y-py)**2>.0002 for px,py,_ in points):points.append((round(x,5),round(y,5),round(min(1.3,.35+size/130),2)))
                if len(points)>=24:break
            layers[filename]=points
        out[group+'/'+folder.name]=layers
p=ROOT/'js/expedition/light_anchors.js'
p.write_text('// Generated by tools/build_light_anchors.py; normalized painted light coordinates.\nADV.Expedition.lightAnchors='+json.dumps(out,separators=(',',':'))+';\n',encoding='utf8')
