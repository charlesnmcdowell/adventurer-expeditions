"""Create runtime catalogue from directed art and verified existing-voice files."""
import json,hashlib
from pathlib import Path
ROOT=Path(__file__).resolve().parents[1]
SRC=ROOT.parent/'adventurer-expeditions-source-art/astra-v12/entrances-20261019'
def main():
 plan=json.loads((SRC/'plan.json').read_text(encoding='utf-8'))
 voices=json.loads((ROOT/'assets/expedition/entrances/voice.json').read_text(encoding='utf-8'))['files']
 for row in voices:
  assert hashlib.sha256((ROOT/row['file']).read_bytes()).hexdigest()==row['sha256']
 actors={}
 for row in plan:
  art=ROOT/'assets/expedition/entrances'/row['actor']/(row['actor']+'.json')
  # Catalogues declare the intended contract even during intake. Missing art
  # fails visibly; it is never silently replaced with a different character.
  actors[row['actor']]={k:v for k,v in row.items() if k not in ['newArt']}
  actors[row['actor']]['art']=row['newArt']
 data=dict(version='20261019-v1',actors=actors,voices={r['id']:r for r in voices})
 (ROOT/'js/expedition/entrance_data.js').write_text('// Generated by tools/build_entrance_data.py; edition-owned.\nADV.Expedition.EntranceData='+json.dumps(data,separators=(',',':'),ensure_ascii=False)+';\n',encoding='utf-8')
 print(len(actors),'entrances;',len(voices),'verified recordings')
if __name__=='__main__':main()
